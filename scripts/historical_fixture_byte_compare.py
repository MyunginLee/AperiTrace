"""Opt-in historical byte diagnostic, NOT the default scientific validation gate.

The Windows-generated canonical_small_v1 archive stays checksum-locked. Fresh
provenance and platform libm differences legitimately change regenerated bytes.
Default tests compare exact identities and tolerant independently computed floats.
This diagnostic reports mismatches without rewriting the historical artifact.
"""

import json
from pathlib import Path

from qc5d.golden import FIXTURE_RELATIVE, fixture_payloads, verify_fixture

ROOT = Path(__file__).resolve().parents[1]


if __name__ == "__main__":
    frozen = ROOT / FIXTURE_RELATIVE
    integrity = verify_fixture(frozen)
    generated = fixture_payloads(ROOT / "configs/canonical_small_fixture_v1.json", ROOT)
    mismatches = [name for name, data in generated.items() if data != (frozen / name).read_bytes()]
    print(
        json.dumps(
            {
                "purpose": "historical Windows byte comparison; not a portable scientific gate",
                "frozen_integrity": integrity,
                "byte_mismatches": mismatches,
                "rewritten_files": [],
            },
            indent=2,
        )
    )
